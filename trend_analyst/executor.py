import logging
import api
from typing import Dict, Any

logger = logging.getLogger(__name__)

async def apply_trend_plan(plan: Dict[str, Any]):
    """
    Applies the execution plan generated by the Trend Analyst.
    - Sets the menu (save_menu MCP tool)
    - Places the bids (closed_bid MCP tool)
    """
    if not plan:
        logger.warning("Empty plan received, nothing to apply.")
        return

    # 1. Update Menu
    menu_items = plan.get("menu", [])
    if menu_items:
        logger.info(f"Applying menu: {menu_items}")
        try:
            resp = await api.call_mcp_tool("save_menu", {"items": menu_items})
            logger.info(f"Menu update response: {resp}")
        except Exception as e:
            logger.error(f"Failed to update menu: {e}")
    else:
        logger.info("No menu items in plan.")

    # 2. Update Bids
    bids_data = plan.get("bids", {})
    if bids_data:
        # Reformat bids from {"Ing": {"amount": X, "quantity": Y}} 
        # to [{"ingredient": "Ing", "bid": X, "quantity": Y}]
        formatted_bids = []
        for ing, details in bids_data.items():
            formatted_bids.append({
                "ingredient": ing,
                "bid": details.get("amount", details.get("bid", 0)),
                "quantity": details.get("quantity", 0)
            })
        
        if formatted_bids:
            logger.info(f"Applying bids: {formatted_bids}")
            try:
                resp = await api.call_mcp_tool("closed_bid", {"bids": formatted_bids})
                logger.info(f"Bids update response: {resp}")
            except Exception as e:
                logger.error(f"Failed to submit bids: {e}")
        else:
            logger.info("No valid bids to apply.")
    else:
        logger.info("No bids in plan.")
